/* 1장 열 개는 위처럼 손으로 찍었다. 그런데 2~8장이 상징물 170개를 더 세운다 —
   자리가 없는 종류는 전부 `|| [-2,-2]` 로 떨어져 **한 칸에 겹쳐 쌓인다.**
   그래서 1장의 열 자리는 그대로 두고(내가 키운 마을이 안 무너지게, DECISIONS 53),
   그 바깥에 고리를 만들어 편 번호 순서로 앉힌다. 손으로 170줄을 더 찍지 않는다. */
const MARK_RING = (() => {
  const used = new Set(Object.values(MARK_D).concat(STELE_D).map(([c, r]) => `${c},${r}`));
  const out = [];
  for (let dc = -30; dc <= 30; dc++) for (let dr = -26; dr <= 26; dr++) {
    const d = vd(dc, dr);
    if (d < 9.5 || d > 26 || used.has(`${dc},${dr}`)) continue;   // 1장 고리(반지름 ~8) 바깥부터
    out.push([dc, dr, d, Math.atan2(dr, dc)]);
  }
  out.sort((a, b) => a[2] - b[2] || a[3] - b[3]);                // 안쪽 고리부터, 고리 안에서는 시계 방향
  return out.filter((_, i) => i % 5 === 0).map(([dc, dr]) => [dc, dr]);   // 성기게 — 이웃과 붙지 않게
})();
const MARK_SEAT = new Set(MARK_RING.map(([c, r]) => `${c},${r}`));
// 편 번호로 앉힌다 — 순서가 바뀌어도 그 상징물은 늘 같은 자리에 선다.
// ⚠ 종류(kind)로 앉히면 두 편이 같은 종류를 쓸 때 겹친다(가마는 2장·4장이 함께 쓴다).
//   그래서 1장 열 편만 손으로 찍은 자리를 쓰고, 그 뒤는 **편 번호**가 자리를 정한다
const markSeat = (kind, no) => (no && no > 10
  ? MARK_RING[no % MARK_RING.length]
  : (MARK_D[kind] || MARK_RING[(no || 0) % MARK_RING.length]));

