/* ── 길과 자리 ───────────────────────────────────────────────────────
   길 둘이 마을 한가운데서 엇갈린다. 칸의 두 축(c 축·r 축)을 그대로 따라가므로
   화면에서 오른쪽아래·왼쪽아래로 비스듬히 뻗는다 = 아이소의 십자로.
   (전에는 화면 가로·세로로 놓았더니 세로길이 수직선이 되어 아이소가 깨졌고,
    그 길가에 붙인 집들이 같은 x 에 겹쳐 탑처럼 쌓였다.)
   집은 길가부터 찬다. 격자로 늘어놓으면 게임 타일맵이 되고, 길에 붙이면 옛 마을이 된다. */
const ROAD_MAX = 21;                                             // 길이 상한 (칸)
// 큰길은 마을 한가운데를 지나고, 샛길은 세 칸 옆으로 비껴간다.
// 정확히 한가운데서 엇갈리면 X 자가 화면을 반듯이 가르고 마을회관이 그 위에 얹힌다 —
// 비껴 놓으면 네거리가 회관 옆의 마당이 되고, 회관은 그 모퉁이에 앉는다
const LANE_C = 4;                                                // 짝수여야 샛길 위 자리가 실제로 비워진다
// 길은 시대를 탄다 (Matto, 09-05): 구석기 막집 터에 길이 나 있으면 이상하다.
// lanes 1 = 다져진 자국 하나(시대 1~2) · lanes 2 = 큰길 + 샛길(시대 3~)
const onRoad = (dc, dr, lanes = 2) =>
  lanes < 2 ? Math.abs(dr) : Math.min(Math.abs(dr), Math.abs(dc - LANE_C));
const HALL_YARD = 1.7;                                           // 마을회관과 그 마당 (반지름, 칸)

// 집 자리 — dc·dr 이 둘 다 짝수인 자리에만. 이러면 이웃 사이가 가로 46px 이라 겹치지 않고
// 사이가 골목이 된다. 길에 가까운 자리부터, 그 다음 한가운데부터 채운다
const mkSlots = (lanes) => {
  const out = [];
  for (let dc = -26; dc <= 26; dc += 2) for (let dr = -22; dr <= 22; dr += 2) {
    const d = vd(dc, dr);
    if (d < HALL_YARD) continue;                                 // 한가운데는 큰 집과 그 마당
    if (Object.values(MARK_D).concat(STELE_D).some(([mc, mr]) => Math.abs(mc - dc) <= 1 && Math.abs(mr - dr) <= 1)) continue;
    if (MARK_SEAT.has(`${dc},${dr}`)) continue;                  // 바깥 고리의 상징물 자리도 비운다
    if (FAC_WHEN.some((f) => Math.abs(f.dc - dc) <= 1 && Math.abs(f.dr - dr) <= 1)) continue;   // 시설 자리
    const road = onRoad(dc, dr, lanes);
    if (road === 0) continue;                                    // 길 위에는 안 짓는다
    // 길에서 두 칸 안이면 벌점이 없고, 멀수록 붙는다. 그 다음이 한가운데서의 거리
    // 길가면 값이 없고 멀수록 벌점 — 다만 거리보다 세면 집이 고리 모양으로 흩어진다
    out.push([dc, dr, d + Math.max(0, road - 2) * 1.2]);
  }
  out.sort((a, b) => a[2] - b[2] || a[0] - b[0]);
  return out.map(([dc, dr]) => [dc, dr]);
};
const SLOTS_1 = mkSlots(1), SLOTS = mkSlots(2);
// e 는 0부터 — 시대 3(e=2)에 나라가 서면서 샛길과 다리가 생긴다
const slotsFor = (e) => (e >= 2 ? SLOTS : SLOTS_1);

/* ── 둘레 — 땅·길·강·밭·숲. 땅에는 테두리가 없다: 틀 밖으로 흘러나가 안개로 사라진다 ── */
function backdrop(state, e) {
  const built = Math.max(state.builds, 1);
  const HZ = OY - 176;                                           // 지평선 — 이 위는 하늘이다
  // 마을이 닿은 반지름 = 쓴 자리 가운데 가장 먼 것. 밭은 그 바깥 고리, 숲은 밭 바깥.
  // 정렬 순서의 마지막 자리를 쓰면 안 된다 — 길가 가중치 때문에 마지막이 가장 먼 자리가 아니다
  const SL = slotsFor(e);
  let rTown = HALL_YARD;
  for (let i = 0; i < Math.min(built, SL.length); i++) rTown = Math.max(rTown, vd(...SL[i]));
  rTown += 1.0;
  const rField = rTown + 0.5, rForest = rField + 2.6;

  // 길 — 가는 선이 아니라 밟아 다져진 땅. 두 축을 따라, 지평선에서 나와 틀 밖으로.
  // 위쪽 끝은 지평선에서 끊는다 — 안 끊으면 길이 하늘과 산을 가로지른다
  const t0 = (HZ - OY) / TH * 2;                                 // 지평선에 닿는 t
  const ROAD = Math.min(ROAD_MAX, rTown + 7);                    // 길은 마을을 따라 자란다
  // 멀어질수록 좁아진다 — 지평선 쪽 끝이 40%. 폭이 일정하면 길이 아니라 띠가 된다
  const road = (u, w1, off) => {
    const q = (t, k) => {
      const s = k * (w1 * (0.4 + 0.6 * (t - t0) / (ROAD - t0)));
      const dc = t * u[0] + s * u[1] + off * u[1], dr = t * u[1] - s * u[0] - off * u[0];
      return `${px(dc, dr).toFixed(0)},${py(dc, dr).toFixed(0)}`;
    };
    const edge = (k) => `M${q(t0, k)} ` + [.25, .5, .75, 1].map((f) => `L${q(t0 + (ROAD - t0) * f, k)}`).join(" ");
    return `<path class="road" d="${edge(1)} ${edge(-1).replace("M", "L").split(" ").reverse().join(" ")} Z"/>`
         + P(edge(1), "roadedge") + P(edge(-1), "roadedge");
  };

  // 강 — c 축을 따라 흐른다(화면에서 오른쪽 아래로). 마을 아래를 지난다
  const rv = (t, k) => `${px(t, k).toFixed(0)},${py(t, k).toFixed(0)}`;
  const river = `<path class="wash" d="M${rv(-46, 16)} L${rv(46, 16)} L${rv(46, 20)} L${rv(-46, 20)} Z"/>`
    + P(`M${rv(-46, 16)} L${rv(46, 16)}`, "mid") + P(`M${rv(-46, 20)} L${rv(46, 20)}`, "thin")
    + `<g class="glint" style="--gt:11s">${P(`M${rv(-10, 18)} q10,-6 20,0 q10,6 20,0`, "thin")}</g>`
    + `<g class="glint" style="--gt:15s">${P(`M${rv(16, 18)} q9,-6 18,0 q9,6 18,0`, "thin")}</g>`;
  // 다리 — 샛길이 강을 건너는 자리. 샛길이 없는 시대(1~2)에는 건널 것도 없다
  const bridge = e < 2 ? "" : `<g transform="translate(${px(LANE_C, 18).toFixed(0)},${py(LANE_C, 18).toFixed(0)})">`
    + P("M-26,-3 L0,-16 L26,-3 L0,10 Z", "fillp") + P("M-20,-6 L-20,-11 M20,-6 L20,-11 M0,-13 L0,-18", "mid") + `</g>`;

  // 밭과 숲 — 마을 둘레의 두 고리. 지평선 위·강 아래에는 아무것도 안 심는다.
  // ⚠ 후보를 먼저 다 모으고 나서 고른다. 루프 순서대로 채우면 왼쪽부터 차서
  //    숲이 고리가 아니라 왼쪽 벽이 된다 (한 번 밟았다)
  const fCand = [], tCand = [];
  for (let dc = -32; dc <= 32; dc += 2) for (let dr = -28; dr <= 28; dr += 2) {
    const h = hash(dc * 131 + dr * 7 + 3);
    // 자리를 흔든다 — 격자 그대로 심으면 숲이 아니라 과수원이 된다
    const x = px(dc, dr) + (h % 19) - 9, y = py(dc, dr) + ((h >> 5) % 13) - 6;
    if (y < HZ + 10 || y > py(0, 15) || x < -50 || x > VW + 50) continue;
    const d = vd(dc, dr);
    if (d < rTown) continue;                                      // 마을 안에는 심지 않는다
    if (d < rForest) { if (FIELD[e] && onRoad(dc, dr) >= 2 && dc % 4 === 0 && dr % 4 === 0) fCand.push([x, y, h]); }
    else tCand.push([x, y, h]);
  }
  const pick = (arr, n) => {                                      // 고르게 솎아 낸다
    if (arr.length <= n) return arr;
    const step = arr.length / n;
    return Array.from({ length: n }, (_, i) => arr[Math.floor(i * step + (arr[Math.floor(i * step)][2] % 3))] || arr[Math.floor(i * step)]);
  };
  const maxTree = Math.min(46, Math.max(16, Math.round(built * .9)));
  const fields = pick(fCand, 22).map(([x, y], i) => `<g transform="translate(${x.toFixed(0)},${y.toFixed(0)})">${FIELD[e](i)}</g>`).join("");
  // 먼 숲은 작게 — 크게 그리면 집을 이긴다 (DECISIONS 54 '나무가 집보다 많다')
  const forest = pick(tCand, maxTree).map(([x, y, h]) => `<g transform="translate(${x.toFixed(0)},${y.toFixed(0)})">${ART.tree(.56 + (h % 22) / 100, h)}</g>`).join("");
  let grass = "";
  // 땅의 결 — 마을과 밭 사이의 빈 고리를 메운다. 이게 없으면 그냥 빈 베이지다.
  // 짧은 담묵 획을 아이소 방향으로 흩는다 (풀·자갈·밟힌 자리)
  for (let i = 0; i < 260; i++) {
    const h = hash("g" + i);
    const dc = ((h % 61) - 30) + ((h >> 7) % 10) / 10, dr = (((h >> 3) % 53) - 26) + ((h >> 11) % 10) / 10;
    const x = px(dc, dr), y = py(dc, dr), d = vd(dc, dr);
    if (y < HZ + 6 || y > py(0, 15.4) || x < -20 || x > VW + 20) continue;
    if (d < HALL_YARD + .4) continue;
    const w = 3 + (h % 5);
    grass += `<path class="thin" d="M${x.toFixed(0)},${y.toFixed(0)} l${w},${(-w / 2).toFixed(1)}"/>`;
  }
  // 땅은 지평선 아래 전체다 — 테두리가 없으니 떠 있는 섬처럼 보이지 않는다
  const ground = `<rect class="earth" x="0" y="${HZ.toFixed(0)}" width="${VW}" height="${(VH - HZ).toFixed(0)}"/>`;
  // 시대 1 은 발자국이 다져 놓은 자국 하나, 2 는 조금 뚜렷한 오솔길, 3부터 큰길과 샛길
  const roads = e === 0 ? road([1, 0], .08, 0)
              : e === 1 ? road([1, 0], .14, 0)
              : road([1, 0], .24, 0) + road([0, 1], .15, LANE_C);
  return ART.scenery(HZ, VW) + ground + grass + roads + river + bridge + fields + forest;
}

// 마을 둘레 — 하늘·산·해·구름·새. 마을만 덩그러니 있으면 종이가 허전하다
function scenery(sy, VW) {
  const k = VW / 1000;
  const ridge = (dip, seed) => {                                       // 능선 한 겹 - 봉우리는 뾰족하고 발치는 낮다
    const n = 5, pts = [];
    for (let i = 0; i <= n; i++) {
      const t = i / n + Math.sin(i * 2.3 + seed) * .05;
      pts.push([t * (VW + 60) - 30, sy - dip * (.14 + .22 * Math.abs(Math.sin(i * 3.1 + seed)))]);
    }
    let d = `M${pts[0][0].toFixed(0)},${pts[0][1].toFixed(0)}`;
    for (let i = 0; i < n; i++) {
      const [x0] = pts[i], [x1, y1] = pts[i + 1];
      const cx = (x0 + x1) / 2 + Math.sin(i * 1.7 + seed) * (x1 - x0) * .2;
      const cy = sy - dip * (.7 + .3 * Math.abs(Math.sin(i * 1.9 + seed)));
      d += ` Q${cx.toFixed(0)},${cy.toFixed(0)} ${x1.toFixed(0)},${y1.toFixed(0)}`;
    }
    return d;                                                          // 열린 능선 - 채움과 선을 따로 쓴다
  };
  const hill = (dip, seed, o) => {                                     // 담채로 채우고 능선만 먹선으로
    const d = ridge(dip, seed);
    return `<path class="hillfill" style="opacity:${o}" d="${d} L${(VW + 30).toFixed(0)},${sy.toFixed(0)} L-30,${sy.toFixed(0)} Z"/>`
         + `<path class="hillline" style="opacity:${(o * .8).toFixed(2)}" d="${d}"/>`;
  };
  const cloud = (fx, fy, w, o) => P(`M${(VW * fx).toFixed(0)},${(sy - fy * k).toFixed(0)} q${(w * .3).toFixed(0)},-13 ${(w * .55).toFixed(0)},-3 q${(w * .26).toFixed(0)},-14 ${(w * .45).toFixed(0)},3 q-${(w * .36).toFixed(0)},8 -${w.toFixed(0)},0`, "thin")
    .replace('class="thin"', `class="thin" style="opacity:${o}"`);
  return `<circle class="sun" cx="${(VW * .8).toFixed(0)}" cy="${(sy - 122 * k).toFixed(0)}" r="${(44 * k).toFixed(0)}"/>
    ${hill(150 * k, .6, .34)}
    ${hill(112 * k, 2.3, .46)}
    ${hill(74 * k, 4.1, .6)}
    ${cloud(.12, 152, 96 * k, .18)}${cloud(.57, 172, 84 * k, .13)}
    <g class="bird" style="--bd:1s;--bw:${VW.toFixed(0)}px">${P(`M0,${(sy - 96 * k).toFixed(0)} q8,-6 15,0 q8,-6 15,0`, "thin")}</g>
    <g class="bird" style="--bd:23s;--bw:${VW.toFixed(0)}px">${P(`M0,${(sy - 70 * k).toFixed(0)} q7,-5 12,0 q7,-5 12,0`, "thin")}</g>`;
}

// 시대마다의 담채 — 그 시대의 재료 빛깔. 시대가 오르면 마을 색조가 통째로 바뀐다.
// (장별 색 --ch1~8 은 1장 안의 시대 1~4 가 전부 같은 색이라 '갈아입었다'가 안 보인다)
// ⚠ 5~12 는 시대 4의 값을 그대로 베껴 둔 자리였다 — 여덟 시대가 같은 색으로 지나갔다.
//   그 시대의 **재료 빛깔**로 정한다: 나무·흙 → 기와·돌 → 청자 → 소나무·회벽 → 저녁의 흙 → 쇠 → 오늘의 하늘.
const ERA_WASH = ["#8C7C66", "#7C8A72", "#6F8A80", "#71798C",
  "#7F8464", "#6E7A85", "#8A7A78", "#5F8A8C", "#6E8470", "#8C7060", "#6B6B72", "#6F8AA0"];

/* ── 렌더 ──
   state: core.villageState 결과. opts.fresh = {builds, life, marks} — 그 수보다 뒤의 것은 붓으로 그어진다. */
function render(host, state, season, opts = {}) {
  const eraInfo = season.eras.find((e) => e.n === state.era) || season.eras[0];
  // ⚠ 전에는 `Math.min(state.era, 4)` 로 못 박혀 있었다 — 시대 5~12(11편~180편)가
  //   통째로 철기 마을의 옷을 입었다. 이제 **그림이 실제로 있는 데까지**를 본다
  //   (village-art.js 가 HOUSE 칸을 채우면 저절로 따라온다).
  const e = Math.min(state.era, HOUSE.length) - 1;

  // 카메라 — 마을 크기를 따라간다. 집이 적을 땐 다가서고(z>1), 자라면 물러난다(z<1).
  // 마을 반지름이 sqrt(집 수)에 비례하므로 z ∝ 1/sqrt(집 수) 면 마을이 틀을 늘 같은 비율로 채운다.
  // 하한 .91 — 그 아래로 물러나면 사람이 14px 밑으로 떨어져 안 읽힌다.
  // 상한 1.3 — 더 다가서면 집 열 채가 화면을 다 먹어 마을이 아니라 집 사진이 된다.
  // z=1 일 때 viewBox 한 칸 = 무대 한 픽셀이고 집은 46px 이다.
  const FW = host.clientWidth || 1128, FH = host.clientHeight || 682;
  const z = Math.max(.91, Math.min(1.3, Math.sqrt(48 / Math.max(state.builds, 6))));
  VW = Math.round(FW / z); VH = Math.round(FH / z);
  OX = Math.round(VW / 2); OY = Math.round(VH * .60);      // 마을 한가운데 = 틀 가운데 조금 아래 (위가 하늘)

  const SL = slotsFor(e);                                  // 시대 1~2 는 샛길이 없으니 그 자리도 비우지 않는다
  const items = [{ dc: 0, dr: 0, html: HALL[e](), kind: "hall", label: HALL_NAME[e], key: "hall" }];

  // 짓기: 문제를 맞힌 수. 일곱에 하나는 나무·세간, 나머지는 집
  for (let i = 0; i < state.builds; i++) {
    const [dc, dr] = SL[i % SL.length];
    const j = hash(dc * 131 + dr * 7), detail = i % 7 === 6;
    items.push({ dc, dr, ox: (j % 9) - 4, oy: ((j >> 4) % 7) - 3, kind: detail ? "detail" : "house",
      html: detail ? DETAIL[e](i) : HOUSE[e](.74 + (j % 26) / 100),
      label: detail ? DETAIL_NAME[e] : HOUSE_NAME[e], key: "b" + i });
  }
  // 상징물 · 비석
  state.marks.forEach((m, i) => {
    const [dc, dr] = markSeat(m.kind, m.no);
    if (MARK[m.kind]) items.push({ dc, dr, html: MARK[m.kind](), kind: m.kind, no: m.no, label: LABEL[m.kind], key: "m" + i });
  });
  state.steles.forEach((era, i) => {
    const [dc, dr] = STELE_D[i % STELE_D.length];
    items.push({ dc, dr, html: MARK.stele(), kind: "stele", no: era, label: LABEL.stele, key: "s" + i });
  });
  // 살리기: 되새김 정답 수. 집 근처 골목에 선다.
  // ⚠ 전에는 `WORK[e][i % 3]` 이라 그 시대 다섯 가지 일 가운데 셋만 나왔다 — 그린 것이 여덟 개나 놀고 있었다.
  // 그리고 셋에 하나는 짝을 지어 앞사람 옆에 선다. 혼자 걷는 사람만 있으면 마을이 안 돌아간다 (Matto, 09-05)
  let prevSeat = null;
  for (let i = 0; i < state.life; i++) {
    const pair = i % 3 === 2 && prevSeat;
    const [dc, dr] = pair || SL[(i * 3) % SL.length];
    // 짐승은 넷에 하나. 종은 i 가 아니라 **짐승 순번**으로 골라야 한다 — i 는 늘 4로 나눠 3이라 한 종만 나온다
    const beast = i % 4 === 3, bi = (i - 3) / 4, work = WORK[e][i % WORK[e].length];
    items.push({ dc: dc + 1, dr, ox: pair ? 14 : 0, oy: pair ? 6 : 0, kind: "life", key: "l" + i,
      html: beast ? ART.animal(bi, state.era) : ART.person(i, work),
      label: beast ? (ART.ANIMAL_NAME ? ART.ANIMAL_NAME(bi, state.era) : "짐승") : (WORK_NAME[work] || "마을 사람") });
    if (!pair) prevSeat = [dc, dr];
  }
  // 시설 — 편을 풀어서 서는 상징물과 다르다. **마을이 자라면 저절로 생기는 것**들이다.
  // 상징물이 「무엇을 배웠나」라면 시설은 「몇 사람이 사나」다 (Matto, 09-05)
  FAC_WHEN.forEach((f) => {
    if (state.era < f.era || state.builds < f.at || !ART.FAC?.[f.key]) return;
    items.push({ dc: f.dc, dr: f.dr, kind: "fac", key: "f" + f.key,
      html: ART.FAC[f.key](), label: ART.FAC_NAME?.[f.key] || f.key });
  });
  // 불 — 구석기 모닥불, 신석기 화덕. 청동기부터는 집 안으로 들어간다
  if (e <= 1) items.push({ dc: 2, dr: 1, html: ART.fire(e), kind: "fire", label: e ? "화덕" : "모닥불", key: "fire" });
  // 빈 터 — 다음 집 자리에 물음표
  if (state.lot) {
    const [dc, dr] = SL[state.builds % SL.length];
    items.push({ dc, dr, kind: "lot", no: state.lot.no, qi: state.lot.qi, key: "lot",
      html: `${P(dia(0, 0, 1.6), "lotpad")}<text class="q" x="0" y="-11" text-anchor="middle">?</text>` });
  }
  items.sort((a, b) => (a.dc + a.dr) - (b.dc + b.dr));     // 뒤에서 앞으로 그린다

  const f = opts.fresh || {};
  const isNew = (k) => (k[0] === "b" && +k.slice(1) >= (f.builds ?? Infinity))
                    || (k[0] === "l" && +k.slice(1) >= (f.life ?? Infinity))
                    || (k[0] === "m" && +k.slice(1) >= (f.marks ?? Infinity));
  host.style.setProperty("--vera", ERA_WASH[state.era - 1] || ERA_WASH[3]);
  host.innerHTML = `<svg viewBox="0 0 ${VW} ${VH}" role="img" aria-label="내 마을, ${eraInfo.name} · 건물 ${state.builds} · 사람 ${state.life}">
    <defs><filter id="vloose" x="-4%" y="-10%" width="108%" height="120%">
      <feTurbulence type="fractalNoise" baseFrequency="0.013 0.05" numOctaves="2" seed="9" result="t"/>
      <feDisplacementMap in="SourceGraphic" in2="t" scale="4" xChannelSelector="R" yChannelSelector="G"/>
    </filter></defs>
    <g class="vback" filter="url(#vloose)">${backdrop(state, e)}</g>
    <g class="vscene">${items.map((it) => it.kind === "lot"
      ? `<g class="lot" data-no="${it.no}" data-qi="${it.qi}" role="button" tabindex="0" aria-label="빈 터, ${it.no}편 되새김 문제" transform="translate(${px(it.dc, it.dr).toFixed(1)},${py(it.dc, it.dr).toFixed(1)})">${it.html}</g>`
      : `<g class="it${isNew(it.key) ? " new" : ""}" data-kind="${it.kind}"${it.no ? ` data-no="${it.no}"` : ""} data-label="${it.label}" role="button" tabindex="0" aria-label="${it.label}" transform="translate(${(px(it.dc, it.dr) + (it.ox || 0)).toFixed(1)},${(py(it.dc, it.dr) + (it.oy || 0)).toFixed(1)})">${it.html}</g>`).join("")}</g>
  </svg>`;
  host.querySelectorAll(".it.new").forEach((g, k) => setTimeout(() => stroke(g), k * 30));
  return { count: items.length };
}

// 붓으로 그어지듯 — 획 길이를 재서 dashoffset 을 푼다. 인주로 그어졌다가 먹으로 앉는다
function stroke(g) {
  if (!g) return;
  [...g.querySelectorAll("path,circle")].forEach((p, k) => {
    if (!p.getTotalLength) return;
    const L = p.getTotalLength();
    p.style.strokeDasharray = L; p.style.strokeDashoffset = L;
    requestAnimationFrame(() => {
      p.style.transition = `stroke-dashoffset .42s cubic-bezier(.22,1,.36,1) ${(k * .04).toFixed(2)}s`;
      p.style.strokeDashoffset = 0;
    });
  });
  setTimeout(() => {
    g.classList.remove("new");
    [...g.querySelectorAll("path,circle")].forEach((p) => { p.style.cssText = ""; });
  }, 900);
}

